// Single source of the pairing vocabulary across the language boundary
// (quality return R5): `crates/devai-ui/src/lan/pair.rs` spells every refusal
// and notice — code, title, hint — ONCE in the `REFUSALS`/`NOTICES` tables;
// this build step renders them into `src/generated/pair-vocabulary.ts`.
//
// Before this script the titles and hints lived twice (Rust and a hand-written
// TS mirror) and the parity test only used `contains`, so a hint could drift
// while both sides still "contained" their own text. Now there is one
// declaration site and the page imports it.
//
// Two consumers:
//   * `npm run gen:codes` / `build` / `typecheck` — regenerate the module (the
//     checked-in file stays current);
//   * `node scripts/gen-pair-vocabulary.mjs --check` — the parity test: fails
//     when the checked-in module is stale, naming the regen command.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

/** The Rust dictionary — the one place the words are spelled. */
export const RUST_PAIR = resolve(HERE, "../../src/lan/pair.rs");
/** The generated TS module the frontend imports. */
export const OUT_FILE = resolve(HERE, "../src/generated/pair-vocabulary.ts");

/** Resolve a quoted literal or the name of a `pub const NAME: &str = "…"`. */
function literal(source, raw) {
  const quoted = /^"([^"]*)"$/.exec(raw.trim());
  if (quoted) return quoted[1];
  const name = raw.trim();
  const constant = new RegExp(`pub const ${name}: &str = "([^"]*)";`).exec(source);
  if (!constant) {
    throw new Error(`\`${name}\` is neither a string literal nor a pub const in pair.rs`);
  }
  return constant[1];
}

/** The rows of one `pub const TABLE: &[Row] = &[ … ];` in pair.rs. */
export function parseTable(source, table) {
  const start = source.indexOf(`pub const ${table}: &[`);
  if (start < 0) throw new Error(`no \`${table}\` table in pair.rs`);
  const open = source.indexOf("[", start);
  const end = source.indexOf("\n];", open);
  if (open < 0 || end < 0) throw new Error(`\`${table}\` is not a closed array`);
  const rows = [];
  for (const block of source.slice(open, end).matchAll(/\w+ \{([^}]*)\}/g)) {
    const fields = block[1];
    const field = (name) => {
      const match = new RegExp(`\\b${name}: ("[^"]*"|[A-Z][A-Z0-9_]*),`).exec(fields);
      if (!match) throw new Error(`a \`${table}\` row has no \`${name}\``);
      return literal(source, match[1]);
    };
    const kind = /\bkind: PairRefusal::(\w+)/.exec(fields);
    rows.push({
      kind: kind ? kind[1] : null,
      code: field("code"),
      title: field("title"),
      hint: field("hint"),
    });
  }
  if (rows.length === 0) throw new Error(`\`${table}\` has no rows`);
  return rows;
}

/** The TS module text for the parsed tables. */
export function renderModule(refusals, notices) {
  const entry = (row) =>
    [
      `    "${row.code}": {`,
      `      code: ${JSON.stringify(row.code)},`,
      `      title: ${JSON.stringify(row.title)},`,
      `      hint: ${JSON.stringify(row.hint)},`,
      "    },",
    ].join("\n");
  const table = (rows) => rows.map(entry).join("\n");
  return [
    "// @generated by scripts/gen-pair-vocabulary.mjs from",
    "// crates/devai-ui/src/lan/pair.rs — DO NOT EDIT.",
    "//",
    "// The refusal and notice vocabulary is spelled ONCE, in Rust (quality",
    "// return R5: the hand-written mirror let titles and hints drift while the",
    "// old parity test only checked `contains`). Regenerate with",
    "// `node scripts/gen-pair-vocabulary.mjs`.",
    "",
    "export const PAIR_VOCABULARY = {",
    "  refusals: {",
    table(refusals),
    "  },",
    "  notices: {",
    table(notices),
    "  },",
    "} as const;",
    "",
    "/** Every reason an invitation can be refused with. */",
    "export type PairReason = keyof typeof PAIR_VOCABULARY.refusals;",
    "",
    "/** Every note the app leaves after an access was granted. */",
    "export type PairNoticeCode = keyof typeof PAIR_VOCABULARY.notices;",
    "",
  ].join("\n");
}

/** Regenerate the module; returns true when the file changed. */
export function generate() {
  const source = readFileSync(RUST_PAIR, "utf8");
  const next = renderModule(parseTable(source, "REFUSALS"), parseTable(source, "NOTICES"));
  let current = null;
  try {
    current = readFileSync(OUT_FILE, "utf8");
  } catch {
    current = null;
  }
  if (current === next) return false;
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, next);
  return true;
}

const invokedDirectly =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  if (process.argv.includes("--check")) {
    const changed = generate();
    if (changed) {
      console.error(
        "pair-vocabulary.ts was stale: crates/devai-ui/src/lan/pair.rs moved and " +
          "the generated module was not refreshed. Run `node scripts/gen-pair-vocabulary.mjs`.",
      );
      process.exit(1);
    }
    console.log("pair-vocabulary.ts is in sync with crates/devai-ui/src/lan/pair.rs");
  } else {
    const changed = generate();
    console.log(
      changed
        ? "regenerated src/generated/pair-vocabulary.ts from lan/pair.rs"
        : "src/generated/pair-vocabulary.ts already in sync",
    );
  }
}
