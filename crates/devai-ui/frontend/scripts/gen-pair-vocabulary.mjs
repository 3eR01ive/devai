// Single source of the pairing vocabulary across the language boundary
// (quality return R5/R6): `crates/devai-ui/data/pair-vocabulary.json` is the
// declarative catalogue — every refusal and notice, code, title and hint,
// ONCE. Rust embeds the same file (`include_str!` in `src/lan/pair.rs`) and
// this build step renders the page's module from it.
//
// Before this script the titles and hints lived twice (Rust and a hand-written
// TS mirror) and the parity test only used `contains`, so a hint could drift
// while both sides still "contained" their own text. Now there is one
// declaration site (data) and the page imports the generated module.
//
// Two consumers:
//   * `npm run gen:codes` / `build` / `typecheck` — regenerate the module (the
//     checked-in file stays current);
//   * `node scripts/gen-pair-vocabulary.mjs --check` — the parity test: fails
//     when the checked-in module is stale, naming the regen command.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

/** The declarative catalogue — the one place the words are spelled. */
export const DATA_FILE = resolve(HERE, "../../data/pair-vocabulary.json");
/** The generated TS module the frontend imports. */
export const OUT_FILE = resolve(HERE, "../src/generated/pair-vocabulary.ts");

/** Parse the catalogue; a malformed row is a hard failure, not a warning. */
export function readVocabulary(file = DATA_FILE) {
  const doc = JSON.parse(readFileSync(file, "utf8"));
  for (const table of ["refusals", "notices"]) {
    if (!Array.isArray(doc[table]) || doc[table].length === 0) {
      throw new Error(`\`${table}\` must be a non-empty array in ${file}`);
    }
    for (const row of doc[table]) {
      for (const field of ["code", "title", "hint"]) {
        if (typeof row[field] !== "string" || row[field].length === 0) {
          throw new Error(`a \`${table}\` row has no \`${field}\` in ${file}`);
        }
      }
    }
  }
  return doc;
}

/** The TS module text for the catalogue. */
export function renderModule(refusals, notices) {
  const entry = (row) =>
    [
      `    "${row.code}": {`,
      `      code: ${JSON.stringify(row.code)},`,
      `      title: ${JSON.stringify(row.title)},`,
      `      hint: ${JSON.stringify(row.hint)},`,
      "    },",
    ].join("\n");
  const table = (rows) => rows.map(entry).join("\n");
  return [
    "// @generated by scripts/gen-pair-vocabulary.mjs from",
    "// crates/devai-ui/data/pair-vocabulary.json — DO NOT EDIT.",
    "//",
    "// The refusal and notice vocabulary is spelled ONCE, in data (quality",
    "// return R5/R6: the hand-written mirror let titles and hints drift while",
    "// the old parity test only checked `contains`). Regenerate with",
    "// `node scripts/gen-pair-vocabulary.mjs`.",
    "",
    "export const PAIR_VOCABULARY = {",
    "  refusals: {",
    table(refusals),
    "  },",
    "  notices: {",
    table(notices),
    "  },",
    "} as const;",
    "",
    "/** Every reason an invitation can be refused with. */",
    "export type PairReason = keyof typeof PAIR_VOCABULARY.refusals;",
    "",
    "/** Every note the app leaves after an access was granted. */",
    "export type PairNoticeCode = keyof typeof PAIR_VOCABULARY.notices;",
    "",
  ].join("\n");
}

/** Regenerate the module; returns true when the file changed. */
export function generate() {
  const doc = readVocabulary();
  const next = renderModule(doc.refusals, doc.notices);
  let current = null;
  try {
    current = readFileSync(OUT_FILE, "utf8");
  } catch {
    current = null;
  }
  if (current === next) return false;
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, next);
  return true;
}

const invokedDirectly =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  if (process.argv.includes("--check")) {
    const changed = generate();
    if (changed) {
      console.error(
        "pair-vocabulary.ts was stale: crates/devai-ui/data/pair-vocabulary.json moved and " +
          "the generated module was not refreshed. Run `node scripts/gen-pair-vocabulary.mjs`.",
      );
      process.exit(1);
    }
    console.log("pair-vocabulary.ts is in sync with crates/devai-ui/data/pair-vocabulary.json");
  } else {
    const changed = generate();
    console.log(
      changed
        ? "regenerated src/generated/pair-vocabulary.ts from data/pair-vocabulary.json"
        : "src/generated/pair-vocabulary.ts already in sync",
    );
  }
}
