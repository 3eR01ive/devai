// Single source of the signature section's word dictionaries across the
// language boundary (rework R8): `crates/devai-api/src/signature/labels.json`
// holds every `token → word` pair ONCE; this build step renders it into
// `src/generated/signature-labels.ts`. No hand-written map exists any more, so
// a token added to the data reaches the UI without anyone copying it, and a
// token added to a Rust enum fails the Rust parity test until the data grows.
//
// Two consumers:
//   * `npm run build` / `npm run check` / `npm run test` — the pre-step
//     regenerates the module (the checked-in file stays current);
//   * `node scripts/gen-signature-labels.mjs --check` — fails when the
//     checked-in module is stale, naming the regen command.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

/** The data file — the one place the words are spelled. */
export const LABELS_JSON = resolve(
  HERE,
  "../../../devai-api/src/signature/labels.json",
);
/** The generated TS module the frontend imports. */
export const OUT_FILE = resolve(HERE, "../src/generated/signature-labels.ts");

/** JSON set name → the TS constant the section imports. */
export const SETS = {
  artifact_status: "ARTIFACT_STATUS_LABELS",
  review_verdict: "REVIEW_VERDICT_LABELS",
  paragraph_source: "PARAGRAPH_SOURCE_LABELS",
  review_paragraph_source: "REVIEW_PARAGRAPH_SOURCE_LABELS",
  denial: "DENIAL_LABELS",
  signature_kind: "SIGNATURE_KIND_LABELS",
  signature_source: "SIGNATURE_SOURCE_LABELS",
};

/** Parse the data file into `{ set: [{ token, word }] }`. */
export function parseLabels(source) {
  const data = JSON.parse(source);
  for (const set of Object.keys(SETS)) {
    if (!Array.isArray(data[set]) || data[set].length === 0) {
      throw new Error(`labels.json carries no non-empty \`${set}\` set`);
    }
  }
  const unknown = Object.keys(data).filter((set) => !(set in SETS));
  if (unknown.length > 0) {
    throw new Error(
      `labels.json carries sets with no TS render: ${unknown.join(", ")}`,
    );
  }
  return data;
}

/** The TS module text for the parsed data. */
export function renderModule(data) {
  const blocks = Object.entries(SETS).map(([set, constant]) => {
    const pairs = data[set];
    const seen = new Set();
    const lines = pairs.map(({ token, word }) => {
      if (seen.has(token)) {
        throw new Error(`duplicate token \`${token}\` in set \`${set}\``);
      }
      seen.add(token);
      return `  ${JSON.stringify(token)}: ${JSON.stringify(word)},`;
    });
    return [
      `export const ${constant}: Record<string, string> = {`,
      ...lines,
      "};",
    ].join("\n");
  });
  return [
    "// @generated by scripts/gen-signature-labels.mjs from",
    "// crates/devai-api/src/signature/labels.json — DO NOT EDIT.",
    "//",
    "// The signature section's words are DATA (rework R8): the Rust tests tie",
    "// this file's token sets to the closed enums, this render ties the UI to",
    "// the same file. Regenerate with `node scripts/gen-signature-labels.mjs`.",
    "",
    ...blocks,
    "",
  ].join("\n");
}

/** Regenerate the module; returns true when the file changed. */
export function generate() {
  const data = parseLabels(readFileSync(LABELS_JSON, "utf8"));
  const next = renderModule(data);
  let current = null;
  try {
    current = readFileSync(OUT_FILE, "utf8");
  } catch {
    current = null;
  }
  if (current === next) return false;
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, next);
  return true;
}

const invokedDirectly =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  if (process.argv.includes("--check")) {
    if (generate()) {
      console.error(
        "signature-labels.ts was stale: crates/devai-api/src/signature/labels.json " +
          "moved and the generated module was not refreshed. Run " +
          "`node scripts/gen-signature-labels.mjs`.",
      );
      process.exit(1);
    }
    console.log("signature-labels.ts is in sync with labels.json");
  } else {
    const changed = generate();
    console.log(
      changed
        ? "regenerated src/generated/signature-labels.ts from labels.json"
        : "src/generated/signature-labels.ts already in sync",
    );
  }
}
