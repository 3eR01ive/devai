// Single source of the homes wire vocabulary across the language boundary
// (R1 quality return): `crates/devai-api/src/codes.rs` spells every machine
// code ONCE; this build step renders it into `src/generated/home-codes.ts`.
// No hand-written mirror exists any more, so a code added in Rust reaches
// the UI without anyone remembering to copy it.
//
// Two consumers:
//   * `npm run build` / `npm run typecheck` / `npm run test` — the pre-step
//     regenerates the module (the checked-in file stays current);
//   * `node scripts/gen-home-codes.mjs --check` — the parity test: fails
//     when the checked-in module is stale, naming the regen command.
//
// Keys are derived mechanically from the constant name (HOME_NO_STORE →
// noStore, HOMES_REGISTRY_CORRUPT → registryCorrupt), so adding a constant
// needs no edit here either.

import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));

/** The Rust dictionary — the one place the tokens are spelled. */
export const RUST_CODES = resolve(HERE, "../../../devai-api/src/codes.rs");
/** The generated TS module the frontend imports. */
export const OUT_FILE = resolve(HERE, "../src/generated/home-codes.ts");

const CONST_RE = /pub const ([A-Z][A-Z0-9_]*): &str = "([^"]+)";/g;

/** Every `pub const NAME: &str = "value";` of codes.rs, in file order. */
export function parseCodes(source) {
  const pairs = [];
  for (const match of source.matchAll(CONST_RE)) {
    pairs.push({ rustName: match[1], value: match[2] });
  }
  return pairs;
}

/** HOME_NO_STORE → noStore; HOMES_REGISTRY_CORRUPT → registryCorrupt. */
export function tsKey(rustName) {
  const stem = rustName.replace(/^HOMES?_/, "").toLowerCase().split("_");
  return (
    stem[0] +
    stem
      .slice(1)
      .filter(Boolean)
      .map((part) => part[0].toUpperCase() + part.slice(1))
      .join("")
  );
}

/** The TS module text for a parsed dictionary. */
export function renderModule(pairs) {
  const seen = new Set();
  const lines = pairs.map(({ rustName, value }) => {
    const key = tsKey(rustName);
    if (seen.has(key)) {
      throw new Error(`two Rust constants render to the TS key "${key}"`);
    }
    seen.add(key);
    return `  ${key}: "${value}",`;
  });
  return [
    "// @generated by scripts/gen-home-codes.mjs from",
    '// crates/devai-api/src/codes.rs — DO NOT EDIT.',
    "//",
    "// The homes machine vocabulary is spelled once, in Rust (R1 quality",
    "// return: the hand-maintained TS mirror let a Rust-only code go unseen).",
    "// Regenerate with `node scripts/gen-home-codes.mjs`.",
    "",
    "export const HOME_CODES = {",
    ...lines,
    "} as const;",
    "",
    "/** Every home machine code the platform can emit on the wire. */",
    "export type HomeCode = (typeof HOME_CODES)[keyof typeof HOME_CODES];",
    "",
    "/** The key a consumer uses to name one code without a string literal. */",
    "export type HomeCodeName = keyof typeof HOME_CODES;",
    "",
  ].join("\n");
}

/** Regenerate the module; returns true when the file changed. */
export function generate() {
  const pairs = parseCodes(readFileSync(RUST_CODES, "utf8"));
  if (pairs.length === 0) {
    throw new Error(`no machine codes found in ${RUST_CODES}`);
  }
  const next = renderModule(pairs);
  let current = null;
  try {
    current = readFileSync(OUT_FILE, "utf8");
  } catch {
    current = null;
  }
  if (current === next) return false;
  mkdirSync(dirname(OUT_FILE), { recursive: true });
  writeFileSync(OUT_FILE, next);
  return true;
}

const invokedDirectly =
  process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url);

if (invokedDirectly) {
  if (process.argv.includes("--check")) {
    const changed = generate();
    if (changed) {
      console.error(
        "home-codes.ts was stale: crates/devai-api/src/codes.rs moved and the " +
          "generated module was not refreshed. Run `node scripts/gen-home-codes.mjs`.",
      );
      process.exit(1);
    }
    console.log("home-codes.ts is in sync with crates/devai-api/src/codes.rs");
  } else {
    const changed = generate();
    console.log(
      changed
        ? "regenerated src/generated/home-codes.ts from codes.rs"
        : "src/generated/home-codes.ts already in sync",
    );
  }
}
